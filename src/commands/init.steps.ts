/**
 * @file init.steps.ts
 * @description Pure steps of `orazaka init`, kept out of the command so each one is small and tested:
 * the .env rendering, the random values injected into a template, the system lines and the missing-directory pass.
 */

import * as crypto from "node:crypto";
import * as fs from "node:fs";
import * as path from "node:path";
import chalk from "chalk";
import type { getSystemInfo } from "../ui/platform";

type SystemInfo = ReturnType<typeof getSystemInfo>;

/** Templates the existing-workspace flow looks for, in order. */
export const ENV_TEMPLATE_NAMES = ["exemple.env.txt", ".env.example", ".env.template"] as const;

export function secureHex(bytes: number): string {
  return crypto.randomBytes(bytes).toString("hex");
}

/** The generated .env: a fixed header, the timestamp, then one KEY=VALUE per default. */
export function renderEnvFile(defaults: Record<string, string>, now: Date): string {
  const lines: string[] = [
    "# ──────────────────────────────────────────────────────",
    "# ORAZAKA ENVIRONMENT CONFIGURATION",
    "# Generated by: npx orazaka init",
    `# Timestamp: ${now.toISOString()}`,
    "# ──────────────────────────────────────────────────────",
    "",
  ];
  for (const [key, value] of Object.entries(defaults)) {
    lines.push(`${key}=${value}`);
  }
  return lines.join("\n");
}

/** The generated keys of a template, each given a fresh random value (database password, crypto key and salt). */
const GENERATED_KEYS: ReadonlyArray<{ key: string; bytes: number }> = [
  { key: "SPRING_DATASOURCE_PASSWORD", bytes: 16 },
  { key: "CRYPTO_KEY", bytes: 16 },
  { key: "CRYPTO_SALT", bytes: 8 },
];

/** A template with fresh random values for the generated keys. */
export function injectGeneratedValues(template: string): string {
  return GENERATED_KEYS.reduce(
    (content, { key, bytes }) => content.replace(new RegExp(`${key}=.*`, "g"), `${key}=${secureHex(bytes)}`),
    template,
  );
}

/** The first env template that exists in the directory, with its content. */
export function findEnvTemplate(targetDir: string): { name: string; content: string } | undefined {
  const name = ENV_TEMPLATE_NAMES.find((candidate) => fs.existsSync(path.join(targetDir, candidate)));
  if (name === undefined) return undefined;
  return { name, content: fs.readFileSync(path.join(targetDir, name), "utf-8") };
}

/** The « System Information » note body. */
export function buildSystemLines(sys: SystemInfo, targetDir: string, toolVersions: string[]): string[] {
  const lines = [
    `${chalk.yellow("Platform")}     ${sys.platform} / ${sys.arch}`,
    `${chalk.yellow("CPU")}          ${sys.cpuModel}`,
    `${chalk.yellow("Memory")}       ${String(sys.totalMemoryGb)} GB`,
    `${chalk.yellow("Node")}         ${sys.nodeVersion}`,
    `${chalk.yellow("Workspace")}    ${targetDir}`,
  ];
  if (sys.isAppleSilicon) {
    lines.push(`${chalk.yellow("Accelerator")}  ${chalk.green("✔ Apple Silicon Metal MPS")}`);
  }
  if (toolVersions.length > 0) {
    lines.push(`${chalk.yellow("Tools")}        ${toolVersions.join(", ")}`);
  }
  return lines;
}

/** Creates the directories that do not exist yet; returns how many it created. */
export function createMissingDirs(dirs: string[], ensure: (dir: string) => void): number {
  const missing = dirs.filter((dir) => !fs.existsSync(dir));
  for (const dir of missing) ensure(dir);
  return missing.length;
}
